function pillowHalf(S, T, sign, seg = 64) {
  const pos = [], idx = [];
  for (let j = 0; j <= seg; j++) {
    for (let i = 0; i <= seg; i++) {
      const u = (i / seg) * 2 - 1, v = (j / seg) * 2 - 1;
      const pinch = 1 - 0.07 * (1 - u * u) * (1 - v * v);
      const x = u * (S / 2) * (1 - 0.05 * (1 - v * v));
      const y = v * (S / 2) * (1 - 0.05 * (1 - u * u));
      const z = sign * T * Math.pow(Math.max(0, 1 - Math.abs(u) ** 2.4), 0.55) * Math.pow(Math.max(0, 1 - Math.abs(v) ** 2.4), 0.55) * pinch;
      pos.push(x, y, z + sign * 1.5 * Math.sin(u * 6) * Math.sin(v * 5) * (1 - u * u) * (1 - v * v));
    }
  }
  for (let j = 0; j < seg; j++) {
    for (let i = 0; i < seg; i++) {
      const a = j * (seg + 1) + i, b = a + 1, c = a + seg + 1, d = c + 1;
      if (sign > 0) idx.push(a, b, d, a, d, c); else idx.push(a, d, b, a, c, d);
    }
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setIndex(idx);
  g.computeVertexNormals();
  return g;
}
function buildCushion() {
  const group = new THREE.Group();
  const fabric = new THREE.MeshPhysicalMaterial({ color: '#d6c3a1', roughness: 0.95, sheen: 0.4, sheenRoughness: 0.85 });
  const S = 406, T = 62;
  const front = new THREE.Mesh(pillowHalf(S, T, 1), fabric);
  const back = new THREE.Mesh(pillowHalf(S, T, -1), fabric);
  front.name = 'Cushion front';
  // piping along the seam
  const edge = [];
  for (let k = 0; k <= 200; k++) {
    const t = k / 200 * 4;
    const side = Math.floor(t) % 4, f = (t % 1) * 2 - 1;
    const [u, v] = [[f, -1], [1, f], [-f, 1], [-1, -f]][side];
    edge.push(new THREE.Vector3(u * (S / 2) * (1 - 0.05 * (1 - v * v)), v * (S / 2) * (1 - 0.05 * (1 - u * u)), 0));
  }
  const piping = new THREE.Mesh(new THREE.TubeGeometry(new THREE.CatmullRomCurve3(edge, true), 240, 3.2, 8, true), fabric);
  [front, back, piping].forEach((m) => { m.castShadow = true; m.receiveShadow = true; });
  group.add(front, back, piping);
  group.rotation.x = -0.12;
  return {
    kind: 'cushion', label: 'Cushion', group, targets: [front, back],
    presets: [
      { id: 'front', label: 'Front', origin: [0, 0, 500], target: [0, 0, 0], size: 300 },
      { id: 'back', label: 'Back', origin: [0, 0, -500], target: [0, 0, 0], size: 300 },
      { id: 'side', label: 'Side seam', origin: [500, 0, 0], target: [S / 2 - 1, 0, 0], size: 70 },
    ],
    applyAppearance(app) {
      fabric.color.set(app.color || '#d6c3a1');
      const velvet = app.finish === 'velvet';
      fabric.sheen = velvet ? 1 : 0.4;
      fabric.sheenRoughness = velvet ? 0.35 : 0.85;
      fabric.sheenColor.copy(fabric.color).lerp(new THREE.Color('#ffffff'), velvet ? 0.5 : 0.2);
    },
    printSurface() { return { roughness: 0.93, sheen: fabric.sheen * 0.5, sheenRoughness: 0.8 }; },
    update() {},
    dispose() { group.traverse((o) => o.isMesh && o.geometry.dispose()); fabric.dispose(); },
  };
}

