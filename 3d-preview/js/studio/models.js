export const ACCEPTED_EXTENSIONS = ['glb', 'gltf', 'obj', 'stl', 'fbx'];
export const MAX_UPLOAD_MB = 100;

export class ModelFileError extends Error {}

function usableNormals(geometry) {
  const position = geometry.attributes.position;
  const normal = geometry.attributes.normal;
  if (!position || !normal || normal.itemSize < 3 || normal.count !== position.count) return false;
  for (let i = 0; i < normal.count; i++) {
    const x = normal.getX(i), y = normal.getY(i), z = normal.getZ(i);
    if (!Number.isFinite(x) || !Number.isFinite(y) || !Number.isFinite(z) || x * x + y * y + z * z < 1e-10) return false;
  }
  return true;
}

export async function loadModelFile(blob, fileName, { maxAnisotropy = 1 } = {}) {
  const ext = (fileName.split('.').pop() || '').toLowerCase();
  if (!ACCEPTED_EXTENSIONS.includes(ext)) {
    throw new ModelFileError(`.${ext} files aren't supported. Upload a .glb, .gltf, .obj, .stl or .fbx file.`);
  }
  if (blob.size > MAX_UPLOAD_MB * 1024 * 1024) {
    throw new ModelFileError(`This file is ${(blob.size / 1048576).toFixed(0)} MB. The limit is ${MAX_UPLOAD_MB} MB; try exporting with compressed textures.`);
  }
  let root;
  try {
    if (ext === 'glb' || ext === 'gltf') {
      const loader = new GLTFLoader();
      const draco = new DRACOLoader();
      draco.setDecoderPath(DRACO_PATH);
      loader.setDRACOLoader(draco);
      loader.setMeshoptDecoder(MeshoptDecoder);
      try {
        const data = await blob.arrayBuffer();
        if (ext === 'gltf') {
          const json = JSON.parse(new TextDecoder().decode(data));
          const external = [...(json.buffers || []), ...(json.images || [])].some((b) => b.uri && !b.uri.startsWith('data:'));
          if (external) throw new ModelFileError('This .gltf points to separate .bin or texture files. Export it as a single .glb file and upload that instead.');
        }
        const gltf = await new Promise((res, rej) => loader.parse(data, '', res, rej));
        root = gltf.scene || gltf.scenes[0];
      } finally {
        draco.dispose();
      }
    } else if (ext === 'obj') {
      root = new OBJLoader().parse(await blob.text());
    } else if (ext === 'stl') {
      const geo = new STLLoader().parse(await blob.arrayBuffer());
      if (!geo.attributes.normal) geo.computeVertexNormals();
      root = new THREE.Mesh(geo, new THREE.MeshPhysicalMaterial({ color: '#d8d8d8', roughness: 0.6 }));
    } else if (ext === 'fbx') {
      root = new FBXLoader().parse(await blob.arrayBuffer(), '');
    }
  } catch (err) {
    if (err instanceof ModelFileError) throw err;
    console.error(err);
    throw new ModelFileError("This file couldn't be read. Check it opens in another 3D viewer, then export it again as .glb.");
  }

  if (!root?.isObject3D) throw new ModelFileError('No 3D scene was found in this file. Export it as a GLB with a scene and try again.');

  const targets = [];
  const originals = new Map();
  let tris = 0;
  root.traverse((o) => {
    if (!o.isMesh) return;
    if (o.isSkinnedMesh || o.morphTargetInfluences?.length) o.frustumCulled = false;
    const g = o.geometry;
    const position = g.attributes.position;
    if (!position?.count) return;
    for (let i = 0; i < position.count; i++) {
      if (!Number.isFinite(position.getX(i)) || !Number.isFinite(position.getY(i)) || !Number.isFinite(position.getZ(i))) {
        throw new ModelFileError('This model has invalid vertex data that can cause flickering. Re-export it as a GLB with transforms applied, then upload it again.');
      }
    }
    if (!usableNormals(g)) {
      g.deleteAttribute('normal');
      g.computeVertexNormals();
    }
    g.computeBoundingBox();
    g.computeBoundingSphere();
    tris += (g.index ? g.index.count : g.attributes.position.count) / 3;
    /* Keep the floor shadow while excluding uploaded surfaces from self-shadow acne. */
    o.castShadow = true;
    o.receiveShadow = false;
    originals.set(o, o.material);
    const materials = Array.isArray(o.material) ? o.material : [o.material];
    materials.forEach((material) => {
      if (!material) return;
      Object.values(material).forEach((value) => {
        if (value?.isTexture) value.anisotropy = Math.max(value.anisotropy || 1, maxAnisotropy);
      });
    });
    targets.push(o);
  });
  if (!targets.length) throw new ModelFileError('No surfaces were found in this file. Check it contains a mesh, not only a camera or rig.');

  const group = new THREE.Group();
  group.add(root);
  const override = new THREE.MeshPhysicalMaterial({ color: '#d8d8d8', roughness: 0.75, sheen: 0.4 });

  return {
    kind: 'upload',
    label: fileName,
    group,
    targets,
    stats: { triangles: Math.round(tris), meshes: targets.length },
    get presets() {
      const box = new THREE.Box3().setFromObject(root);
      const c = box.getCenter(new THREE.Vector3());
      const s = box.getSize(new THREE.Vector3());
      const far = Math.max(s.x, s.y, s.z) * 3;
      const size = Math.min(s.x, s.y) * 0.35;
      return [
        { id: 'front', label: 'Front', origin: [c.x, c.y, c.z + far], target: [c.x, c.y, c.z], size },
        { id: 'back', label: 'Back', origin: [c.x, c.y, c.z - far], target: [c.x, c.y, c.z], size },
        { id: 'left', label: 'Left', origin: [c.x - far, c.y, c.z], target: [c.x, c.y, c.z], size: Math.min(s.z, s.y) * 0.35 },
        { id: 'right', label: 'Right', origin: [c.x + far, c.y, c.z], target: [c.x, c.y, c.z], size: Math.min(s.z, s.y) * 0.35 },
        { id: 'top', label: 'Top', origin: [c.x, c.y + far, c.z], target: [c.x, c.y, c.z], size: Math.min(s.x, s.z) * 0.35 },
      ];
    },
    options: { override: true },
    applyAppearance(app) {
      override.color.set(app.color || '#d8d8d8');
      for (const [mesh, mat] of originals) mesh.material = app.override ? override : mat;
    },
    printSurface() { return { roughness: 0.7, metalness: 0 }; },
    update() {},
    dispose() {
      root.traverse((o) => {
        if (o.isMesh) {
          o.geometry.dispose();
          const ms = Array.isArray(o.material) ? o.material : [o.material];
          ms.forEach((m) => { Object.values(m).forEach((v) => v && v.isTexture && v.dispose()); m.dispose(); });
        }
      });
      override.dispose();
    },
  };
}

export async function buildTemplate(kind, params = {}) {
  if (templateById(kind)?.garment) return buildGarment(kind);
  if (kind === 'mug') return buildMug(params);
  if (kind === 'phonecase') return buildPhoneCase(params);
  if (kind === 'tote') return buildTote();
  if (kind === 'cushion') return buildCushion();
  if (kind === 'frame') return buildFrame();
  throw new Error(`Unknown template "${kind}"`);
}
