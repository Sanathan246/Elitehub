function buildTote() {
  const group = new THREE.Group();
  const canvas = new THREE.MeshPhysicalMaterial({ color: '#e7dbc3', roughness: 0.96, sheen: 0.5, sheenRoughness: 0.9, side: THREE.DoubleSide });
  const W = 380, H = 420;
  const g = new THREE.BoxGeometry(W, H, 2, 40, 44, 1);
  const p = g.attributes.position;
  for (let i = 0; i < p.count; i++) {
    const x = p.getX(i), y = p.getY(i), z = p.getZ(i);
    const u = x / (W / 2), v = y / (H / 2);
    // puffed in the middle, flat at the seams; a little sag and a few soft wrinkles
    const puff = 26 * Math.pow(Math.max(0, 1 - u * u), 0.55) * Math.pow(Math.max(0, 1 - Math.pow(Math.max(0, v), 2)), 0.5) * (v < 0 ? 1 - 0.35 * v * v : 1);
    const wrinkle = 1.6 * Math.sin(u * 7 + v * 3) * Math.sin(v * 9) * (1 - u * u);
    p.setZ(i, Math.sign(z) * (1.2 + puff + wrinkle));
    p.setX(i, x * (1 - 0.025 * (1 - v * v)));
    if (y > H / 2 - 1) p.setY(i, y + 2.5 * Math.sin(u * 3.2));
  }
  g.computeVertexNormals();
  const bag = new THREE.Mesh(g, canvas);
  bag.name = 'Tote';
  const strap = (z) => {
    const curve = new THREE.CatmullRomCurve3([
      new THREE.Vector3(-72, H / 2 - 30, z), new THREE.Vector3(-80, H / 2 + 90, z * 1.6),
      new THREE.Vector3(-40, H / 2 + 255, z * 1.2), new THREE.Vector3(0, H / 2 + 280, z),
      new THREE.Vector3(40, H / 2 + 255, z * 1.2), new THREE.Vector3(80, H / 2 + 90, z * 1.6),
      new THREE.Vector3(72, H / 2 - 30, z),
    ]);
    const tg = new THREE.TubeGeometry(curve, 120, 6, 10, false);
    tg.scale(1, 1, 0.45);
    tg.translate(0, 0, z * 0.55);
    const m = new THREE.Mesh(tg, canvas);
    m.castShadow = true;
    return m;
  };
  bag.castShadow = true; bag.receiveShadow = true;
  group.add(bag, strap(4.5), strap(-4.5));
  return {
    kind: 'tote', label: 'Tote bag', group, targets: [bag],
    presets: [
      { id: 'front', label: 'Front', origin: [0, -10, 400], target: [0, -10, 0], size: 230 },
      { id: 'back', label: 'Back', origin: [0, -10, -400], target: [0, -10, 0], size: 230 },
      { id: 'side', label: 'Side panel', origin: [300, -10, 0], target: [W / 2 - 2, -10, 0], size: 54 },
    ],
    applyAppearance(app) { canvas.color.set(app.color || '#e7dbc3'); },
    printSurface() { return { roughness: 0.95, sheen: 0.25, sheenRoughness: 0.9 }; },
    update() {},
    dispose() { group.traverse((o) => o.isMesh && o.geometry.dispose()); canvas.dispose(); },
  };
}

